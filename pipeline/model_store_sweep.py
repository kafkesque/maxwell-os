def _rule_fixture(**over) -> dict:
    """One mutated copy of a valid rule, so a control can fire on ONE declared field (BUG-492)."""
    base = {"offered_classes": ["SHADOW", "ORPHAN"], "owner_word_prefix": "D-", "order": DECLARED_ORDER,
            "copy_policy": COPY_POLICY, "receipt_dir": "governance", "receipt_prefix": "DELETION_RECEIPT_",
            "receipt_suffix": ".json", "verify_digest": True}
    base.update(over)
    return base


def selftest() -> int:
    """Known-answer controls over the licence, the shape and the declared order - touching no store, ever."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        base = pathlib.Path(tmp)
        repo = base / "hub" / "models--x--y"
        repo.mkdir(parents=True)
