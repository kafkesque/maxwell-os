#!/usr/bin/env python3
"""build_anchor_v8_remap_triage.py — anchor-only v8 domain remap (D-2866), silver excluded.

Authoritative anchor source = discipline_anchor_rederived_v7_20261007.json (201 rows).
This is the D-2853 close-out artifact: the `research & methodology -> research practice` rename
is ALREADY applied. What remains for v8 is:

  DROP  science & research   (A-merge into research practice; keep co-present applied domains)
  DROP  social sciences      (B-demote to raw synonyms under research practice)
  ROUTE only when a row EMPTIES after drops -> discipline's practical domain (D2D map)

The earlier "research-practice-only leftover -> route" rule was WRONG (owner rejected it):
philosophy / cultural-studies / measurement anchors legitimately carry `research practice`
(the application IS scholarship). Corrected map: philosophy + cultural studies -> research practice.

OWNER_OVERRIDES = owner-adjudicated final v8 domains (2026-10-07). These are the only rows where
the deterministic DROP/ROUTE is superseded. R031/R085/R164 stay `research practice` (no change)
and drop out; owner may still prefer `education` for R031/R085 -> add override if confirmed.

SILVER (gold_4axis/gold_frozen/stage2_fewshot) regenerated by S4. Legacy ANCHOR_208_CONSOLIDATED
is a different generation (86 discipline disagreements) -> regenerate, never hand-patch.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REDERIVED = ROOT / "governance" / "discipline_anchor_rederived_v7_20261007.json"
MAP_CFG = ROOT / "config" / "discipline_domain_map.yaml"
OUT = ROOT / "governance" / "anchor_v8_domain_remap_triage_20261007.csv"

RENAME = {"research & methodology": "research practice"}
DROP = {"science & research", "social sciences"}
cfg = yaml.safe_load(MAP_CFG.read_text(encoding="utf-8"))
D2D = cfg["map"]
FALLBACK = cfg["fallback"]

# Owner-adjudicated final v8 domains (2026-10-07). Supersede deterministic routing.
OWNER_OVERRIDES = {
    "R004": ["legal & public policy"],                        # OK
    "R198": ["personal productivity", "finance & investment", "entrepreneurship"],  # owner 2026-10-07 (NOT marketing)
    "R065": ["media & entertainment"],                        # prior approval
    "R107": ["education", "user experience", "research practice"],  # owner
    "R162": ["organizational behavior", "education", "leadership"],  # owner 2026-10-07 (NOT legal & public policy)
    "R184": ["health & wellness"],                            # owner 2026-10-07 (NOT organizational behavior)
    "R085": ["emerging"],                                     # owner: metacognition/self-awareness -> abstain
    "R210": ["education", "user experience", "marketing & communications"],  # owner 2026-10-07 (add mktg as 3rd)
}


def _dedupe(items):
    seen, out = set(), []
    for x in items:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def remap(discipline, domains):
    """Return (proposed, change_type, removed). change_type in {DROP, ROUTED, None}."""
    kept = _dedupe([RENAME.get(d, d) for d in domains if RENAME.get(d, d) not in DROP])
    removed = [d for d in domains if RENAME.get(d, d) in DROP]
    if not kept:
        return [D2D.get(discipline, FALLBACK)], "ROUTED", removed
    if removed:
        return kept, "DROP", removed
    return kept, None, []


def main():
    rows = json.loads(REDERIVED.read_text())["rows"]
    out = []
    for r in rows:
        proposed, ctype, removed = remap(r["discipline"], r["domains"])
        if r["item_id"] in OWNER_OVERRIDES:
            proposed = OWNER_OVERRIDES[r["item_id"]]
            ctype = "ROUTED" if ctype is None else ctype
        if ctype is None:
            continue
        if proposed == r["domains"]:  # no-op: skip
            continue
        out.append({
            "item_id": r["item_id"],
            "name": r.get("name") or "",
            "discipline": r["discipline"],
            "old_domains": json.dumps(r["domains"], ensure_ascii=False),
            "proposed_domains": json.dumps(proposed, ensure_ascii=False),
            "change_type": ctype,
            "removed": ";".join(removed),
            "ruling": "owner" if r["item_id"] in OWNER_OVERRIDES else "",
        })

    fields = ["item_id", "name", "discipline", "old_domains",
              "proposed_domains", "change_type", "removed", "ruling"]
    with open(OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(out)

    from collections import Counter
    dead = {v for o in out for v in json.loads(o["proposed_domains"]) if v in DROP | set(RENAME)}
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} anchor rows "
          f"({dict(Counter(o['change_type'] for o in out))})")
    print("rows:")
    for o in out:
        print(f"   {o['item_id']:6} {o['discipline'][:20]:20} {o['old_domains']:44} -> "
              f"{o['proposed_domains']}  [{o['change_type']}{' / owner' if o['ruling'] else ''}]")
    print(f"VALIDATION dead-in-proposed={len(dead)} "
          f"empty={sum(1 for o in out if not json.loads(o['proposed_domains']))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
