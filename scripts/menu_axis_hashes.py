#!/usr/bin/env python3
"""scripts/menu_axis_hashes.py - split the COMPOSITE menu_hash by declared axis group (BUG-447/BUG-453).

WHY: config/closed_menu_v6.json is a composite of 7 sub-objects and pipeline.closed_menu.menu_hash() hashes
all of them, yet config/closed_menu_v5.sha256 was consumed as the ANSWER-SPACE PIN. One hash, two meanings:
a discipline-definition edit (D-321, the BUG-357 fix) moved the pin although the answer space
(43 canonical domains + the `emerging` abstention slot) moved by ZERO slots. D-285 recorded that "taxonomy
discipline definitions feed the closed menu"; D-321 asserted "the menu was not touched".

RAIL: emit a hash per axis, so an answer-space claim is checkable against the answer space and a definition
edit can never be mistaken for a slot change. Reuses pipeline.closed_menu (C21 - a second implementation of
the rendering would be a second truth). Group membership is DECLARED in config/menu_axis_groups.yaml and read
from there (C12): this generator must not carry its own copy of the list.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from pipeline.closed_menu import canonical_json, live_menu_path, menu_hash  # noqa: E402

MENU = live_menu_path()   # LIVE menu: per-axis + answer-space hashing (D-2853/v7)
SHA = REPO / "config" / "closed_menu_v5.sha256"   # HISTORICAL composite pin (D-371): never re-rendered
FROZEN_MENU = REPO / "config" / "closed_menu_v5.json"  # HISTORICAL menu the retired answer-space pin was minted from
GROUPS = REPO / "config" / "menu_axis_groups.yaml"
OUT = REPO / "config" / "menu_axis_hashes.yaml"
ANSWER_GROUP = "answer_space"


def axis_hash(menu: dict, axis: str) -> str:
    """sha256 of the canonical rendering of ONE axis. Never hashes any other axis. Raises KeyError if absent."""
    return hashlib.sha256(canonical_json({axis: menu[axis]}).encode()).hexdigest()


def axis_value_set(menu: dict, axis: str) -> object:
    """The answer SLOTS of one axis - the `value` field only, never the definition/description/group wording.

    BL3/D-NEW-1 (2026-10-05): the answer space is the SET of canonical values a classifier may EMIT, which is
    the `value` field, not the whole entry. Hashing the whole entry made (a) a discipline-definition reword move
    the answer pin (the BUG-447 mirror) and (b) a discipline-slot addition invisible to the pin (BL3). For a
    scalar axis (the `abstention` token) the value IS the scalar. Raises KeyError if absent.
    """
    if isinstance(menu[axis], str):
        return menu[axis]
    return sorted(e["value"] for e in menu[axis])


def load_groups() -> dict[str, list[str]]:
    """The declared axis->group membership, from the ONE declaration both readers share.

    Raises:
        KeyError: if the declaration has no `axis_groups` block. A generator that defaults its own grouping is
            the defect this file exists to prevent.
    """
    doc = yaml.safe_load(GROUPS.read_text(encoding="utf-8"))
    return {g: list(axes) for g, axes in doc["axis_groups"].items()}


def main() -> int:
    """Print and (re)write config/menu_axis_hashes.yaml with a per-axis hash map."""
    menu: dict = json.loads(MENU.read_text(encoding="utf-8"))
    frozen = SHA.read_text(encoding="utf-8").strip()
    groups = load_groups()
    answer_axes = groups[ANSWER_GROUP]
    live_composite = menu_hash()
    per_axis = {a: axis_hash(menu, a) for a in sorted(menu)}
    answer = hashlib.sha256(canonical_json({a: axis_value_set(menu, a) for a in answer_axes}).encode()).hexdigest()
    # D-NEW-6: the HISTORICAL answer-space pin (8436d9c9...) under the RETIRED D-371 method - the FULL domain
    # entries plus the abstention token (2 axes), NOT the live 5-axis value set. Emitted so the manifest's
    # historical answer_space_sha256 is checked against a pin of the SAME method, never the live pin (a category
    # error). Reproducible from config/closed_menu_v5.json; never re-derived from the live menu.
    frozen_menu = json.loads(FROZEN_MENU.read_text(encoding="utf-8"))
    frozen_answer = hashlib.sha256(canonical_json({
        "domains": frozen_menu["domains"],
        "abstention": frozen_menu["abstention"],
    }).encode()).hexdigest()
    lines = [
        f"# menu_axis_hashes.yaml - PER-AXIS hashes of {MENU.relative_to(REPO)} (BUG-447/BUG-453).",
        "# Generated by scripts/menu_axis_hashes.py. Never edit by hand; never hash a subset by hand.",
        "schema_version: '1.0'",
        "generated: '2026-09-25'",
        f"source: {MENU.relative_to(REPO)}",
        "axis_groups_source: config/menu_axis_groups.yaml",
        "axis_group:",
    ]
    for g, axes in groups.items():
        lines.append(f"  {g}: [{', '.join(axes)}]")
    # hashes: is a LIST of records, NOT a map keyed by axis name. MEASURED 2026-09-25: the menu axis
    # named 'decision' sat in KEY position, so the decision-citation rail in scripts/reconcile.py read a
    # sha256 as a decision id and the only way to keep it calm was a declared EXEMPTION
    # (config/reconciliation.yaml#meta.citation_exemptions). An exemption is a place where a rail stops
    # looking (D-402/BUG-483). A name in VALUE position cannot collide with a KEY vocabulary, so the
    # collision is removed by construction instead of tolerated - and no future axis name can recreate it.
    lines.append("hashes:")
    for a in sorted(per_axis):
        lines.append(f"  - axis: {a}")
        lines.append(f"    sha256: {per_axis[a]}")
    lines += [
        "answer_space_hash: " + answer,
        "answer_space_method: five_axis_value_set_v1",
        "answer_space_axes: " + json.dumps(answer_axes),
        "answer_space_hash_frozen_pin: " + frozen_answer,
        "answer_space_method_frozen: domains_full_plus_abstention_v1",
        "composite_hash_live: " + live_composite,
        "composite_hash_frozen_pin: " + frozen,
        "note: >-",
        "  D-285 measured that taxonomy discipline definitions feed the composite menu_hash, and D-321",
        "  changed a discipline definition while asserting 'the menu was not touched'. Both are true:",
        "  the DEFINITION moved, the ANSWER SPACE did not. D-371: the composite is HISTORICAL and is",
        "  never re-rendered; the answer space is the pin. D-NEW-1 (2026-10-05): the answer-space pin is",
        "  hashed over the VALUE SET (canonical slots) of the answer_space axes, never the definition",
        "  wording - a slot add/rename moves the pin, a wording edit does not (BL3 / BUG-447 mirror).",
        "  D-NEW-6 (2026-10-05): answer_space_hash_frozen_pin (8436d9c9...) is the HISTORICAL answer-space stamp",
        "  minted under the RETIRED D-371 method (domains full entries + abstention token, 2 axes). It is emitted",
        "  here so the manifest's historical answer_space_sha256 is compared against a pin of the SAME method,",
        "  not the live 5-axis value-set pin (which would be a category error). Never re-derive it as live.",
    ]
    payload = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        # A CHECK MUST NOT WRITE (BUG-491 class). MEASURED 2026-09-25: running this script WITH --check wrote the
        # file it was asked to check, so a stale per-axis hash file was silently repaired instead of reported -
        # and a stale declaration makes the depth-domain gate compare the live render against OLD hashes (a
        # blindspot, not just a cosmetic mode collapse). --check now reports and refuses to repair.
        if not OUT.exists():
            print("FAIL: " + str(OUT.relative_to(REPO)) + " is ABSENT - a pin that does not exist cannot be "
                  "compared; generate it with scripts/menu_axis_hashes.py (no flag)", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != payload:
            print("FAIL: " + str(OUT.relative_to(REPO)) + " is STALE - the declared per-axis hashes no longer "
                  f"describe {MENU.relative_to(REPO)}, so any answer-space claim checked against them is checked "
                  "against the wrong bytes. Regenerate with scripts/menu_axis_hashes.py (no flag).", file=sys.stderr)
            return 1
        print("ok  " + str(OUT.relative_to(REPO)) + " is in sync with the live menu bytes")
        return 0
    # ROUTED THROUGH THE GUARD (D-401/I1, 2026-09-25). MEASURED: this file was written with a bare
    # Path.write_text - no fsync, no os.replace - on the ONE config artifact that IS the answer-space pin, so a
    # crash mid-write could truncate the pin itself (C6). A document has no cells, so the only legal declaration
    # is a whole-file regeneration: OWNED_ANY, which must be explicit and is refused if omitted.
    from lib import write_guard  # noqa: E402 - the ownership invariant is ENFORCED, not restated (C12)
    write_guard.write_document(OUT, payload, writer="scripts/menu_axis_hashes.py",
                               owned_keys={write_guard.OWNED_ANY}, journal=True)
    print(f"frozen composite pin : {frozen[:16]}")
    print(f"frozen answer pin    : {frozen_answer[:16]}  (retired D-371 method)")
    print(f"live composite       : {live_composite[:16]}   {'MATCH' if live_composite==frozen else 'DRIFT (BUG-447, DEFINITION only)'}")
    print(f"answer_space_hash    : {answer[:16]}  over {answer_axes}")
    for a in sorted(per_axis):
        print(f"  {a:18s} {per_axis[a][:16]}")
    print(f"wrote {OUT.relative_to(REPO)}")
    try:
        from pipeline.closed_menu import render_closed_menu
        live = render_closed_menu()
        for g, axes in groups.items():
            moved = [a for a in axes if axis_hash(menu, a) != axis_hash(live, a)]
            print(f"drift in {g}:", moved or "none")
    except Exception as exc:  # noqa: BLE001 - report, never swallow (C16)
        print(f"live render unavailable: {type(exc).__name__}: {exc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
