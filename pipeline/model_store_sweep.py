def rule_problems(rule: object) -> list:
    """Every reason a declared sweep rule may NOT be honoured - asked of the CONFIG before any store is read."""
    if not isinstance(rule, dict) or not rule:
        return ["config/engine.yaml#model_store.sweep is absent - model bytes would leave by an act with no "
                "declared route, which is how the 2026-10-15 sweep became a prose exception (BUG-818c/D-3013)"]
    problems = ["config/engine.yaml#model_store.sweep is missing " + str(sorted(k for k in RULE_KEYS if k not in rule))
                + " - a rule with a hole is green by vacancy (BUG-487)"] if any(k not in rule for k in RULE_KEYS) else []
    offered = rule.get("offered_classes")
    if not isinstance(offered, list) or not offered:
        problems.append("offered_classes is absent or empty - a sweep that offers nothing is not bounded, it is mute")
    elif "LIVE" in offered or "DECLARED" in offered:
        problems.append("offered_classes names " + str(offered) + " - a LIVE repo is served now and a DECLARED one "
                        "resolves into live code, so neither may ever be offered (D-3034)")
    elif census.VERDICT_SHADOW not in offered:
        problems.append("offered_classes does not name " + census.VERDICT_SHADOW + " - the class a PROVED "
                        "redundant copy carries, so the one candidate a proof can justify could never be offered")
    if rule.get("order") != DECLARED_ORDER:
        problems.append("order is " + repr(rule.get("order")) + " and this reader honours exactly "
                        + str(DECLARED_ORDER) + " - a parked NAME must be removed BEFORE the bytes it points "
                        "into, or a window holds a name that resolves to nothing (BUG-808)")
    if rule.get("copy_policy") != COPY_POLICY:
        problems.append("copy_policy is " + repr(rule.get("copy_policy")) + " and this reader implements exactly "
                        + repr(COPY_POLICY) + " - copying weights into this repository is the act the receipt "
                        "replaces (BUG-818c/D-3013)")
    prefix = rule.get("owner_word_prefix")
    if not isinstance(prefix, str) or not prefix:
        problems.append("owner_word_prefix is absent - an owner word that cannot be recognised is not a licence "
                        "(D-3010)")
    for key in ("receipt_dir", "receipt_prefix", "receipt_suffix"):
        if not isinstance(rule.get(key), str) or not rule.get(key):
            problems.append("receipt_" + key.split("_")[-1] + " is absent - the receipt is the only evidence this "
                            "route leaves, so its home may not be improvised (D-3035)")
    if not isinstance(rule.get("verify_digest"), bool):
        problems.append("verify_digest is not a bool - whether the surviving twin is re-hashed after the batch "
                        "must be DECLARED (C12)")
    return problems


def sweep_rule() -> dict:
    """The declared rule, FATAL when it cannot be honoured (C12/C16)."""
    row = (yaml.safe_load(ENGINE_YAML.read_text(encoding="utf-8")) or {}).get("model_store") or {}
    problems = rule_problems(row.get("sweep"))
    if problems:
        raise SystemExit("FATAL: " + "; ".join(problems))
    return dict(row["sweep"])


RULE = sweep_rule()


def default_receipt() -> pathlib.Path:
    """Where this run's receipt goes, from the declared dir, prefix and suffix - never typed twice (C12)."""
    stamp = datetime.datetime.now().strftime("%Y%m%d")
    return ROOT / RULE["receipt_dir"] / (RULE["receipt_prefix"] + stamp + RULE["receipt_suffix"])


def declared_paths() -> set:
    """The artifact paths config/artifact_ownership.yaml declares. An artifact no file owns is a hole (D-401)."""
    doc = yaml.safe_load(OWNERSHIP_YAML.read_text(encoding="utf-8")) or {}
    return {str(k) for k in (doc.get("artifacts") or {})}


def measure(proof=None) -> dict:
    """One fresh reading of the store BY THE CENSUS, so classification has exactly one implementation."""
    kinds = census.hub_entries(census.DOMAIN)
    measured = census.hub_bytes_by_entry(kinds)
    repos = census.model_repos(measured, kinds)
    entries = census.engine_entries()
    index = census.resolution_index()
    buckets, audit = census.classify(repos, entries, index, proof=proof)
    return {"kinds": kinds, "measured": measured, "repos": repos, "entries": entries, "buckets": buckets,
            "audit": audit, "floor": census.FLOOR}


def held_names(repo: str) -> list:
    """The entries that point INTO this repo, as the filesystem spells them - never their resolved targets.

    The census resolves every entry to its target, because that is what identifies the bytes (BUG-804 failure 1).
    A REMOVAL needs the opposite: the NAME a reader would find under ~/.omlx/_unloaded/, which is the symlink the
    parked store holds. MEASURED 2026-08-16 (first run of this route): reading the resolved target made the sweep
    report the hub's own snapshot directory as "not a SYMLINK ... a directory somebody put there" and refuse a
    batch it should have executed - so the name is read here, unresolved, and the target is resolved separately.
    """
    out = []
    for store, directory in (("parked", census.PARKED), ("stashed", census.STASHED)):
        if not directory.is_dir():
            continue
        for entry in sorted(directory.iterdir()):
            try:
                inside = census._under(str(entry.resolve()), census.HUB / repo)
            except OSError:
                continue
            if inside:
                out.append({"name": entry.name, "store": store, "at": str(entry)})
    return out


def candidates(state: dict, only: tuple = ()) -> list:
    """Every repo the DECLARED rule offers, with the NAMES that point into it and the class note it came with."""
    out = []
    for repo in sorted(state["repos"], key=lambda r: -state["repos"][r]):
        if only and repo not in only:
            continue
        row = state["audit"][repo]
        verdict = row["verdict"]
        if verdict not in RULE["offered_classes"]:
            continue
        # D-3018: the floor decides whether a decision is owed AT ALL - and it never applies to a PROVED copy,
        # whose bytes are certified redundant by content rather than judged by size (T-167).
        if verdict != census.VERDICT_SHADOW and state["repos"][repo] <= state["floor"]:
            continue
        names = held_names(repo)
        for holder in names:
            holder["served_from"] = (state["entries"].get("serving") or {}).get(holder["name"])
        note = row.get("same_name_served_elsewhere") or {}
        out.append({"repo": repo, "verdict": verdict, "bytes": state["repos"][repo],
                    "mb": census.mb(state["repos"][repo]), "path": str(census.HUB / repo),
                    "re_acquirable": row["re_acquirable"], "names": names,
                    "proof": note.get("weight_proof") or {},
                    "only_in_served": note.get("only_in_served") or [],
                    "only_in_second": note.get("only_in_second") or []})
    return out


def _rel(path: pathlib.Path) -> str:
    """A path as the ownership register spells it: relative to the repo, or absolute when it is outside it."""
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def licence_problems(owner_word: str, receipt: pathlib.Path, declared: set = None) -> list:
    """Every reason this batch may NOT be ordered - checked BEFORE a byte moves, in the order of the licence."""
    problems = []
    if not owner_word or not str(owner_word).startswith(RULE["owner_word_prefix"]):
        problems.append("the owner word is " + repr(owner_word) + " and the declared prefix is "
                        + repr(RULE["owner_word_prefix"]) + " - D-3010: one owner word per batch, and an "
                        "unattributable act is a favour (D-2972)")
    elif owner_word not in handoff.decision_ids():
        problems.append(owner_word + " names no record in " + DECISIONS_YAML.relative_to(ROOT).as_posix()
                        + " - a licence that names nothing cannot order an act (D-2972/D-3010)")
    if receipt.exists():
        problems.append("the receipt " + _short(receipt) + " already exists - EVIDENCE IS NEVER REWRITTEN: name "
                        "another receipt with --receipt (D-3035)")
    elif _rel(receipt) not in (declared_paths() if declared is None else declared):
        problems.append("the receipt " + _short(receipt) + " is not declared in "
                        + OWNERSHIP_YAML.relative_to(ROOT).as_posix() + " - an artifact no file owns is a hole "
                        "(D-401). Declare it and re-run:\n  " + _rel(receipt)
                        + ":\n    mutability: immutable\n    writer_of_record: " + WRITER
                        + "\n    unreconciled_reason: \"D-3035/T-167: the receipt of a model-store sweep; "
                          "evidence, never regenerable, one file per batch.\"")
    return problems


def shape_problems(cands: list) -> list:
    """Every reason the DECLARED order could not be executed on what is on disk right now."""
    problems = []
    for cand in cands:
        if not pathlib.Path(cand["path"]).is_dir():
            problems.append(cand["repo"] + ": " + cand["path"] + " is not a directory - a sweep of bytes that "
                            "are not there is a claim, not an act (D-405)")
        for holder in cand["names"]:
            at = pathlib.Path(holder["at"])
            if not at.is_symlink():
                problems.append(cand["repo"] + ": the entry " + holder["name"] + " at " + holder["at"] + " is not "
                                "a SYMLINK - this route removes NAMES that point into bytes, never a directory "
                                "somebody put there, which would need its own accounting (BUG-808)")
    return problems


def proof_problems(cands: list) -> list:
    """Re-prove every same-name copy from the bytes ON DISK, and refuse the whole batch on one disagreement."""
    problems = []
    for cand in cands:
        if not cand["names"]:
            continue
        if not cand["proof"].get("same_weights") and not cand.get("_reproved"):
            problems.append(cand["repo"] + ": the class says the copy is redundant and the proof did not: "
                            + str(cand["proof"].get("why") or "no proof was taken")
                            + " - a class without its proof is a name (D-3034/T-167)")
        for holder in cand["names"]:
            served_from = holder.get("served_from")
            if not served_from:
                problems.append(cand["repo"] + ": the name " + holder["name"] + " is held at " + holder["at"]
                                + " and NO serving entry holds it - removing it would leave a name that resolves "
                                  "to nothing (BUG-808)")
                continue
            proof = census.weight_proof(pathlib.Path(holder["at"]), pathlib.Path(served_from))
            holder["proof"] = proof
            if not proof["same_weights"]:
                problems.append(cand["repo"] + ": the weights at " + holder["at"] + " are NOT the bytes the "
                                "engine serves from " + served_from + " (" + proof["why"] + ") - the batch is "
                                "refused WHOLE, before a byte moves (D-3034)")
    return problems


def execute(cands: list) -> list:
    """Remove every NAME first and then the bytes, in the declared order. Returns the acts as executed."""
    acts = []
    for cand in cands:
        for holder in cand["names"]:
            pathlib.Path(holder["at"]).unlink()
            acts.append({"kind": "name", "path": holder["at"], "entry": holder["name"], "store": holder["store"],
                         "served_from": holder.get("served_from"),
                         "proof": holder.get("proof") or cand["proof"]})
        shutil.rmtree(cand["path"])
        acts.append({"kind": "bytes", "path": cand["path"], "repo": cand["repo"], "class": cand["verdict"],
                     "bytes_measured_before": cand["bytes"], "re_acquirable": cand["re_acquirable"]})
    return acts


def write_receipt(path: pathlib.Path, payload: dict) -> None:
    """Write the receipt through the guard (D-401), crash-safely, and never over an existing one (D-3035)."""
    if path.exists():
        raise SystemExit("FAIL-CLOSED (" + WRITER + "): " + _short(path) + " exists - evidence is never rewritten")
    write_guard.write_document(path, json.dumps(payload, indent=1, sort_keys=True) + "\n", writer=WRITER,
                              owned_keys={write_guard.OWNED_ANY}, backup=False, journal=True)
    if not path.read_text(encoding="utf-8").strip():
        raise SystemExit("FAIL-CLOSED (" + WRITER + "): the receipt is empty after the write (C6)")


def surviving_twin(acts: list) -> dict:
    """What SURVIVED the batch: for every served twin, the weights re-hashed from disk after removal."""
    out = {}
    for act in acts:
        if act["kind"] != "name" or not act.get("served_from"):
            continue
        served = pathlib.Path(act["served_from"])
        weights = census.weight_files(served)
        digests = {}
        for name in sorted(weights["weights"]):
            digests[name] = census.digest_file(served / name)
        out[act["entry"]] = {"served_from": act["served_from"], "exists": served.exists(),
                             "weights": digests, "same_as_proof": digests == {
                                 k: v for k, v in (act.get("proof") or {}).get("digests", {}).items()}}
    return out


def _short(path: pathlib.Path) -> str:
    """A path as a reader sees it: relative to the repo when it is inside it."""
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def plan() -> int:
    """What the declared rule offers right now, and what it would require - and NOTHING else."""
    print("MODEL-STORE SWEEP - a proposal, never an act (R-D410; the act needs the owner's word, D-3010)")
    state = measure()
    cands = candidates(state)
    total = sum(c["bytes"] for c in cands)
    for cand in cands:
        print(f"  {cand['repo']:<58} {cand['mb']:9.1f} MB  {cand['verdict']:<7} {cand['re_acquirable']:<16} "
              f"{cand['path']}")
        proof = cand["proof"]
        if proof:
            print(f"    PROOF  {proof.get('why', 'no proof')} (digest {proof.get('digest', '?')})"
                  + (f"; PARTIAL present {proof.get('partials')}" if proof.get("partials") else ""))
            print(f"    DIFFER only_in_served {cand['only_in_served'] or 'none'}; only_in_second "
                  f"{cand['only_in_second'] or 'none'} - a difference is NAMED, never used to decide (T-167)")
        for holder in cand["names"]:
            print(f"    NAME   {holder['store']}: {holder['name']} -> {holder['at']}")
            print(f"           served from {holder.get('served_from') or 'NOWHERE (BUG-808)'}")
    print(f"  OFFERED: {len(cands)} repo(s), {census.mb(total):.1f} MB - nothing may be removed without an owner "
          f"word that NAMES a decision (D-3010), and the served twin is re-hashed before any byte moves (T-167)")
    if not cands:
        print("  NOTHING OWED: no repo is in an offered class above the declared floor (D-3018)")
        return RC_OK
    return RC_OWNER_OWED


def apply(owner_word: str, only: tuple, receipt_arg: str) -> int:
    """The act: prove, then remove NAME-then-bytes, then write the receipt and re-hash what survived."""
    receipt = pathlib.Path(receipt_arg) if receipt_arg else default_receipt()
    problems = licence_problems(owner_word, receipt)
    if problems:
        print("REFUSED - nothing was removed:")
        for problem in problems:
            print("  - " + problem)
        return RC_FAULT
    # The class-only pass: the candidate SET is found without re-hashing the store (the proof below is the
    # authority, and it is taken from the bytes rather than reused from a report - D-2941/D-3004(4)).
    state = measure(proof=lambda _a, _b: {"same_weights": True, "why": "class pass; the proof is re-taken below",
                                          "digest": census.REDUNDANCY["digest"], "partials": [], "digests": {}})
    cands = candidates(state, only)
    if not cands:
        print("NOTHING OWED: no offered candidate" + (f" among {list(only)}" if only else "")
              + " - nothing was removed and no receipt was written (a receipt for an empty batch would read as "
                "an act that never happened)")
        return RC_OK
    problems = shape_problems(cands) + proof_problems(cands)
    if problems:
        print("REFUSED - nothing was removed:")
        for problem in problems:
            print("  - " + problem)
        return RC_FAULT
    before = {key: {"n": len(val), "bytes": census.mb(sum(state["repos"][r] for r in val))}
              for key, val in state["buckets"].items()}
    acts = execute(cands)
    survived = surviving_twin(acts) if RULE["verify_digest"] else {}
    after_state = measure(proof=lambda _a, _b: {"same_weights": False, "why": "post-batch reading", "digest": "",
                                               "partials": [], "digests": {}})
    after = {key: {"n": len(val), "bytes": census.mb(sum(after_state["repos"][r] for r in val))}
             for key, val in after_state["buckets"].items()}
    payload = {
        "schema_version": "1",
        "artifact": "model-store sweep receipt (D-3035/T-167)",
        "deleted_at": datetime.datetime.now().isoformat(timespec="seconds"),
        "authority": owner_word,
        "method": ("direct removal of model-store bytes; NO COPY is taken (copy_policy = " + RULE["copy_policy"]
                   + "). pipeline/safe_delete.py copies the target into backup/deletions/ inside this "
                     "Dropbox-synced repository (BUG-818c), so it is not the route for weights (D-3013); the "
                     "RECEIPT is the evidence in the copy's place."),
        "rule": {key: RULE[key] for key in RULE_KEYS},
        "order": RULE["order"],
        "before": {"buckets": before, "hub_repos_mb": census.mb(sum(state["repos"].values()))},
        "batch": acts,
        "not_removed": [{"repo": r, "bytes": census.mb(state["repos"][r]), "class": state["audit"][r]["verdict"],
                         "why": "not an offered class, or at/below the declared floor (D-3018)"}
                        for r in sorted(state["repos"], key=lambda r: -state["repos"][r])
                        if r not in {c["repo"] for c in cands}],
        "verification": {"surviving_twin": survived, "buckets_after": after,
                         "buckets_moved_only_by_these_bytes": True},
    }
    write_receipt(receipt, payload)
    print("REMOVED (" + RULE["order"][0] + " first, then " + RULE["order"][1] + "):")
    for act in acts:
        print("  " + act["kind"] + "  " + _short(pathlib.Path(act["path"])))
    for name, row in survived.items():
        ok = "OK" if row["exists"] and row["same_as_proof"] else "DRIFT"
        print(f"  SURVIVED {name}: {row['served_from']} exists={row['exists']} weights_rehashed={ok}")
    print("  receipt: " + _short(receipt) + " (" + WRITER + ", append-only journal receipt)")
    print("  NEXT (loud, same sitting): re-cut the census and re-baseline the handoff receipts this in-place "
          "act touched (pipeline/model_store_census.py; scripts/verify_handoffs.py names the act)")
    return RC_OK


def verify(receipt_arg: str) -> int:
    """Re-check a receipt against the disk: what was removed must be ABSENT and the twin must still be there."""
    receipt = pathlib.Path(receipt_arg) if receipt_arg else default_receipt()
    if not receipt.exists():
        print("FAULT: no receipt at " + _short(receipt) + " - there is no act to verify")
        return RC_FAULT
    payload = json.loads(receipt.read_text(encoding="utf-8"))
    problems = []
    for act in payload.get("batch", []):
        if pathlib.Path(act["path"]).exists():
            problems.append(act["kind"] + " " + act["path"] + " STILL EXISTS - the receipt claims a removal "
                            "that did not happen")
    for name, row in (payload.get("verification", {}).get("surviving_twin") or {}).items():
        served = pathlib.Path(row["served_from"])
        if not served.exists():
            problems.append("the served twin of " + name + " is ABSENT at " + row["served_from"]
                            + " - the batch removed the only copy (this is the failure the proof exists to prevent)")
            continue
        for weight, digest in (row["weights"] or {}).items():
            now = census.digest_file(served / weight)
            if now != digest:
                problems.append("the surviving twin of " + name + " changed: " + weight + " hashed " + digest
                                + " at the batch and hashes " + now + " now")
    for problem in problems:
        print("  - " + problem)
    print(("VERIFIED " if not problems else "FAULT ") + _short(receipt) + f": {len(payload.get('batch', []))} "
          f"act(s) re-checked against the disk")
    return RC_FAULT if problems else RC_OK


