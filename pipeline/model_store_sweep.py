#!/usr/bin/env python3
"""pipeline/model_store_sweep.py - the ONE route by which MODEL-STORE bytes leave the disk (T-167/D-3035).

WHY THIS IS NOT pipeline/safe_delete.py (MEASURED 2026-10-15, BUG-818c/D-3013). safe_delete.py protects
PIPELINE OUTPUT and its protocol COPIES the target into backup/deletions/ inside this Dropbox-synced repository
before removing it. For model weights that copy is a second 4 GB inside the repo - on 2026-10-15 the 12.4 GB
sweep was therefore executed by hand under an exception recorded in PROSE
(governance/DELETION_RECEIPT_20261015.json#method), i.e. an act with no route. This module is the route: the
copy is REPLACED BY A RECEIPT, because the bytes being removed are the second copy of a model the engine still
serves, and the receipt is the evidence that cannot be regenerated by re-downloading 4 GB.

WHAT IT REFUSES (each one measured, not assumed):
  * a class the config does not offer. config/engine.yaml#model_store.sweep.offered_classes is READ, a LIVE repo
    may never appear there (the engine serves it now) and a DECLARED one resolves into live code (D-3034);
  * a same-name copy proved by NAME. Every weight file of the served twin is re-hashed NOW, from the bytes on
    disk, and ONE differing or missing digest refuses the WHOLE batch before a byte moves (D-3034: redundant by
    BYTES, never by name);
  * a removal the owner has not ordered. The owner's word must NAME a record that exists in
    config/decisions.yaml (D-3010: one word per batch), and a licence that names nothing is a favour (D-2972);
  * a NAME left pointing into nothing. A parked name is removed BEFORE the bytes it points into, so no window
    holds an entry that resolves to an absent target (BUG-808), and an entry that is not a symlink is refused
    rather than followed;
  * a receipt that already exists. Evidence is never rewritten (D-3035); a second batch names a second receipt;
  * an undeclared receipt path. config/artifact_ownership.yaml owns who may write what (D-401), and this module
    REFUSES - before removing anything - printing the declaration it needs, rather than leaving an artifact no
    file owns.

Exit codes (BUG-457 tri-state): 0 = nothing owed (or the act succeeded); 1 = a FAULT (a refused batch, an
undeclared rule); 2 = bytes an owner must dispose of (--plan found candidates and no word was given).

Usage:
  python3 pipeline/model_store_sweep.py --plan
  python3 pipeline/model_store_sweep.py --apply --owner-word D-3035 [--repo <stem>]... [--receipt <path>]
  python3 pipeline/model_store_sweep.py --verify-only [--receipt <path>]
  python3 pipeline/model_store_sweep.py --selftest
"""
