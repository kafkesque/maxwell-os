def _run_cases(cases: list) -> int:
    """Run the controls and print the count. Kept apart from selftest() so the synthetic tree is still there."""
    failures = 0
    for label, predicate in cases:
        try:
            ok = bool(predicate())
        except Exception as exc:  # noqa: BLE001 - a control that raises IS a failed control, and it is named
            ok, label = False, label + " (raised " + type(exc).__name__ + ": " + str(exc) + ")"
        print(("  ok   " if ok else "  FAIL ") + label)
        failures += 0 if ok else 1
    print(f"model-store-sweep: {len(cases) - failures}/{len(cases)} known-answer control(s) fire")
    return RC_FAULT if failures else RC_OK


def main(argv: list) -> int:
    """--plan (default), --apply with the owner's word, --verify-only against a receipt, or --selftest."""
    if "--selftest" in argv:
        return selftest()
    if "--verify-only" in argv:
        position = argv.index("--receipt") if "--receipt" in argv else -1
        return verify(argv[position + 1] if position >= 0 and position + 1 < len(argv) else "")
    if "--apply" in argv:
        word, receipt, only = "", "", []
        for position, arg in enumerate(argv):
            if arg == "--owner-word" and position + 1 < len(argv):
                word = argv[position + 1]
            elif arg == "--receipt" and position + 1 < len(argv):
                receipt = argv[position + 1]
            elif arg == "--repo" and position + 1 < len(argv):
                only.append(argv[position + 1])
        return apply(word, tuple(only), receipt)
    return plan()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
