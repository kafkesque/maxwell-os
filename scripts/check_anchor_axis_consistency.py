#!/usr/bin/env python3
"""check_anchor_axis_consistency.py — the ANCHOR five-axis PROPAGATION rail.

WHY THIS EXISTS (the blindspot it closes)
-----------------------------------------
The ANCHOR family is read through AT LEAST five artifacts that are regenerated by
DIFFERENT scripts at DIFFERENT times:

  * governance/ANCHOR_150_FIVE_AXIS_VIEW_20260927.csv        (five-axis CVS, 150 rows)
  * governance/ANCHOR_208_FIVE_AXIS_VIEW_20260930.csv        (five-axis CSV, 208 rows)
  * governance/ANCHOR_208_DEPTH_CORRECTED_20261002.json      (depth authority, D-2760)
  * governance/ANCHOR_208_DISCIPLINE_NORMALIZED_20261002.json (normalised view)
  * governance/ANCHOR_208_CONSOLIDATED_20261002.json         (merged verdicts)
  * governance/depth_anchor_conformance_20261002.json        (gold: depth gate)
  * governance/discipline_anchor_rederived_v8_20261007.json  (gold: discipline/domain authority, D-2868)

Nothing asserted that they AGREE. So a correction landed in one (the owner's
D-2795 30-anchor discipline re-label, 12 rows) while the others stayed stale —
and the S4 golden few-shot derived from the stale copy would silently carry a
label the gold disagrees with. That is an error leak, not a cosmetic drift.

WHAT IT DOES
------------
For each axis, `config/anchor_axis_authority.yaml` names ONE authority artifact.
The rail re-derives that axis for every declared CONSUMER and compares on the
item_id intersection. Verdicts:

  exit 0  every consumer agrees with the authority on every axis
  exit 2  drift exists but EVERY drifting cell is DECLARED (owner-owed, counted,
          ceiling SHRINK-ONLY) — loud, never fatal (BUG-457 pattern)
  exit 1  UNDECLARED drift (a silent propagation failure), or a declared cell
          that now AGREES (the ceiling must shrink loudly, never hide a fix)

C12: every path, column, cohort and normaliser comes from
`config/anchor_axis_authority.yaml` — no literal in this file.
C16: a missing input is a hard failure that names the file, never a skipped axis.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
from lib import artifact_encoding  # noqa: E402 - D-2646: the decode rule has ONE home
CONFIG = REPO / "config" / "anchor_axis_authority.yaml"


def _collapse(value: object) -> str:
    """Normalise a cell: collapse whitespace, keep an empty cell empty.

    A list (the ruler's `domains` column) is pipe-joined so the AUTHORITY's list form compares
    equal to a consumer's `domain` string — one canonical serialisation for the axis (D-2866).
    """
    if isinstance(value, (list, tuple)):
        return "|".join(" ".join(str(v).split()) for v in value if v)
    if value is None:
        return ""
    return " ".join(str(value).split())


def _load_rows(path: Path, kind: str, rows_key: str | None) -> dict[str, dict]:
    """Load {item_id: row} from a csv file, a json list, or a json {rows_key: [...]}.

    Raises:
        FileNotFoundError: the declared artifact does not exist (C16, never skip).
        ValueError: the artifact parsed but carried no rows.
    """
    if not path.exists():
        raise FileNotFoundError(f"check_anchor_axis_consistency: declared artifact missing: {path}")
    if kind == "csv":
        with artifact_encoding.open_artifact(path, REPO) as handle:
            rows = list(csv.DictReader(handle))
    else:
        payload = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(payload, list):
            rows = payload
        elif isinstance(payload, dict):
            key = rows_key or "rows"
            rows = payload.get(key)
            if rows is None:
                raise ValueError(f"check_anchor_axis_consistency: {path} has no '{key}' key")
        else:
            raise ValueError(f"check_anchor_axis_consistency: {path} is not a list or mapping")
    if not rows:
        raise ValueError(f"check_anchor_axis_consistency: {path} carried no rows")
    out: dict[str, dict] = {}
    for row in rows:
        iid = _collapse(row.get("item_id"))
        if iid:
            out[iid] = row
    if not out:
        raise ValueError(f"check_anchor_axis_consistency: {path} carried no item_id values")
    return out


def _depth_map(config: dict) -> dict[str, str]:
    """Read the numeric<->label depth map from the declared depth menu (C12)."""
    menu = yaml.safe_load((REPO / config["depth_menu"]).read_text(encoding="utf-8"))
    return {str(cls["id"]): cls["label"] for cls in menu["classes"]}


def _axis_value(row: dict, column: str, normalizer: str, depth_map: dict[str, str]) -> str:
    """Read one axis cell and normalise it to the comparable form."""
    raw = _collapse(row.get(column))
    if normalizer == "depth_numeric_to_label":
        raw = depth_map.get(raw, raw)
    return raw


def _collect(config: dict) -> tuple[list[dict], dict[str, dict[str, dict]]]:
    """Load every declared artifact once.

    Returns (diffs, cache) where diffs is the list of drifting cells.
    """
    depth_map = _depth_map(config)
    cache: dict[str, dict[str, dict]] = {}
    diffs: list[dict] = []

    def rows_for(spec: dict) -> dict[str, dict]:
        key = spec["file"]
        if key not in cache:
            cache[key] = _load_rows(REPO / key, spec.get("kind", "csv"), spec.get("rows_key"))
        return cache[key]

    for axis, spec in config["axes"].items():
        authority = spec["authority"]
        authority_rows = rows_for(authority)
        for consumer in spec.get("consumers", []):
            consumer_rows = rows_for(consumer)
            for iid in sorted(set(authority_rows) & set(consumer_rows)):
                want = _axis_value(authority_rows[iid], authority["column"],
                                   authority.get("normalizer", ""), depth_map)
                got = _axis_value(consumer_rows[iid], consumer["column"],
                                  consumer.get("normalizer", ""), depth_map)
                if want == got:
                    continue
                if not want and not got:
                    continue
                diffs.append({
                    "axis": axis,
                    "item_id": iid,
                    "authority_file": authority["file"],
                    "authority_value": want,
                    "consumer_file": consumer["file"],
                    "consumer_value": got,
                })
    return diffs, cache


def _key(row: dict) -> tuple[str, str, str]:
    """The declared-drift identity: axis + item + consumer file."""
    return (row["axis"], row["item_id"], row["consumer_file"])


def _coverage(config: dict, cache: dict[str, dict[str, dict]]) -> list[str]:
    """Report the item_id intersection size per axis (a cohort mismatch must be SEEN)."""
    lines: list[str] = []
    for axis, spec in config["axes"].items():
        authority_rows = cache[spec["authority"]["file"]]
        for consumer in spec.get("consumers", []):
            consumer_rows = cache[consumer["file"]]
            inter = len(set(authority_rows) & set(consumer_rows))
            lines.append(
                f"    {axis:15s} {len(authority_rows):>3d} vs {len(consumer_rows):>3d} -> {inter:>3d} joined"
                f"  ({Path(consumer['file']).name})"
            )
    return lines


def _emerging_abstention_guard(config: dict) -> int:
    """D-2870 fail-closed: the catch-all abstention token must never coexist with a concrete
    domain in the same anchor list.  'emerging' is an AXIS-LEVEL verdict (open-set rejection),
    not a token that can sit beside 'education' etc. (law of non-contradiction on one axis)."""
    tax = yaml.safe_load((REPO / "config" / "taxonomy_v8.yaml").read_text(encoding="utf-8"))
    catch_all = tax["meta"]["catch_all_domain"]
    axis = config.get("axes", {}).get("domain")
    if not axis:
        return 0
    path = REPO / axis["authority"]["file"]
    # C12/BUG-492: the column's NAME comes from the declared authority, never from a literal. A hardcoded
    # key here would silently scan ZERO rows the day the authority's schema changes - a guard that cannot
    # fire is a comment, and a vacuous green is worse than no guard at all.
    column = axis["authority"].get("column", "domain")
    rows = json.loads(path.read_text(encoding="utf-8"))
    data = rows.get("rows", rows if isinstance(rows, list) else [])
    violations: list[tuple[str, list[str]]] = []
    for r in data:
        dom = r.get(column)
        if isinstance(dom, str):
            toks = [t.strip() for t in dom.split("|") if t.strip()]
        elif isinstance(dom, list):
            toks = [str(t) for t in dom]
        else:
            continue
        if catch_all in toks and len(toks) > 1:
            violations.append((str(r.get("item_id", "?")), toks))
    if violations:
        print(f"  FAIL  {len(violations)} anchor(s) carry catch-all '{catch_all}' beside a "
              f"concrete domain (abstention is axis-level, never a co-token):")
        for iid, toks in violations:
            print(f"    {iid}: {toks}")
        return 1
    print(f"  ok  catch-all '{catch_all}' never coexists with a concrete domain "
          f"({len(data)} rows scanned)")
    return 0


def main() -> int:
    """CLI entry point: --check (default), --selftest, --emit-declared."""
    parser = argparse.ArgumentParser(description="ANCHOR five-axis propagation rail")
    parser.add_argument("--selftest", action="store_true", help="prove the rail FIRES on synthetic drift")
    parser.add_argument("--emit-declared", action="store_true", help="print the current drift as YAML to declare")
    args = parser.parse_args()

    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))

    guard_rc = _emerging_abstention_guard(config)
    if guard_rc:
        return guard_rc

    if args.selftest:
        return _selftest(config)
    if args.emit_declared:
        diffs, _ = _collect(config)
        print("declared_drift:")
        for row in sorted(diffs, key=lambda r: (r["axis"], r["item_id"], r["consumer_file"])):
            print(f"  - axis: {row['axis']}")
            print(f"    item_id: {row['item_id']}")
            print(f"    consumer_file: {row['consumer_file']}")
            print(f"    authority_value: {row['authority_value']!r}")
            print(f"    consumer_value: {row['consumer_value']!r}")
            print(f"    why: OWED - propagate the authority value into this derived artifact")
        print(f"# total drifting cells: {len(diffs)}")
        return 0

    diffs, cache = _collect(config)
    declared = {_key(r): r for r in config.get("declared_drift", [])}
    ceiling = config.get("declared_drift_ceiling")

    undeclared = [r for r in diffs if _key(r) not in declared]
    now_agreeing = [k for k in declared if k not in {_key(r) for r in diffs}]

    print("check_anchor_axis_consistency: declared coverage (authority vs consumer item_id joins)")
    for line in _coverage(config, cache):
        print(line)

    if not diffs:
        print(f"  ok  every consumer agrees with its declared authority; "
              f"declared ceiling {ceiling} is SHRINK-ONLY and now holds 0")
        return 0

    if undeclared:
        print(f"  FAIL  {len(undeclared)} UNDECLARED drifting cell(s) "
              f"- a silent propagation failure (a correction landed in one artifact only):")
        for row in undeclared[:40]:
            print(f"    {row['axis']:15s} {row['item_id']:6s} authority={row['authority_value']!r} "
                  f"vs {Path(row['consumer_file']).name}={row['consumer_value']!r}")
        return 1

    print(f"  owner-owed (loud, not fatal - BUG-457): {len(diffs)} declared drifting cell(s), "
          f"ceiling {ceiling} (shrink-only)")
    for row in sorted(diffs, key=lambda r: (r["axis"], r["item_id"]))[:40]:
        print(f"    {row['axis']:15s} {row['item_id']:6s} "
              f"{Path(row['consumer_file']).name}: {row['consumer_value']!r} != {row['authority_value']!r}")
    if now_agreeing:
        print(f"  DRIFT  {len(now_agreeing)} declared cell(s) now AGREE - REMOVE them from "
              f"declared_drift (the ceiling must shrink loudly, never hide a fix):")
        for axis, iid, consumer in now_agreeing:
            print(f"    {axis:15s} {iid:6s} {Path(consumer).name}")
        return 2
    if ceiling is not None and len(diffs) > ceiling:
        print(f"  FAIL  declared drift {len(diffs)} exceeds the declared ceiling {ceiling} (shrink-only)")
        return 1
    return 2


def _selftest(config: dict) -> int:
    """Prove the comparison FIRES: a synthetic disagreement must be SEEN, an agreement must not.

    A control nothing runs is a comment (BUG-492).
    """
    failures: list[str] = []
    authority = {"column": "discipline", "normalizer": ""}
    consumer = {"column": "discipline", "file": "synthetic.csv"}
    depth_map = {"1": "universal", "4": "specialized"}

    want = _axis_value({"discipline": "philosophy"}, authority["column"], "", depth_map)
    got_same = _axis_value({"discipline": "philosophy"}, consumer["column"], "", depth_map)
    got_diff = _axis_value({"discipline": "emerging"}, consumer["column"], "", depth_map)
    if want != got_same:
        failures.append("selftest: identical values were reported as a disagreement")
    if want == got_diff:
        failures.append("selftest: a real disagreement was NOT seen")
    if _axis_value({"depth": "4"}, "depth", "depth_numeric_to_label", depth_map) != "specialized":
        failures.append("selftest: the depth numeric->label normaliser did not fire")
    if _axis_value({"discipline": "  a   b "}, "discipline", "", depth_map) != "a b":
        failures.append("selftest: whitespace normalisation did not fire")

    for record in config.get("selftest_controls", []):
        if record.get("expect") == "fires" and _collapse(record.get("a")) == _collapse(record.get("b")):
            failures.append(f"selftest: control {record.get('name')} expected to differ but did not")

    if failures:
        for failure in failures:
            print(f"  FAIL  {failure}")
        return 1
    print("  ok  check_anchor_axis_consistency --selftest: disagreement SEEN, agreement quiet, "
          "depth normaliser fired, whitespace normalised")
    return 0


if __name__ == "__main__":
    sys.exit(main())
