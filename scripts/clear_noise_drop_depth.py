#!/usr/bin/env python3
"""clear_noise_drop_depth.py — D-2813: depth does NOT apply to a noise_drop row.

Deterministic, LLM-free, config-driven, crash-safe (C6), fail-closed (C16).

For every declared noise_drop row (`config/owner_domain_rulings_20261008.yaml`
-> `noise_drop_excluded`), clear the DEPTH axis in every depth face:

  * DEPTH_CORRECTED (the depth AUTHORITY, 208 rows): depth=None, depth_label=None,
    depth_source='owner_finalized_noise_drop' (the D-2760 sentinel — a provenance
    marker, never a depth class).
  * depth_anchor_conformance (golden few-shot): the row is REMOVED from `examples`
    and appended to `excluded` (a noise_drop row is a valid exemplar on NO axis).
    `counts` and the depth-map input sha256 are recomputed so the artifact stays
    self-consistent.
  * both five-axis views: the `depth` column is cleared to '' (mirrors R021).

CONSOLIDATED is NOT touched here: it is regenerated by
`scripts/regenerate_anchor_208_v8.py`, which reads DEPTH_CORRECTED as its depth
source, so the clear propagates deterministically.

Usage:
    python3 scripts/clear_noise_drop_depth.py            # dry-run report
    python3 scripts/clear_noise_drop_depth.py --apply    # write
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import sys
import tempfile
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

DEPTH = ROOT / "governance" / "ANCHOR_208_DEPTH_CORRECTED_20261002.json"
CONFORMANCE = ROOT / "governance" / "depth_anchor_conformance_20261002.json"
VIEW_208 = ROOT / "governance" / "ANCHOR_208_FIVE_AXIS_VIEW_20260930.csv"
VIEW_150 = ROOT / "governance" / "ANCHOR_150_FIVE_AXIS_VIEW_20260927.csv"
RULINGS = ROOT / "config" / "owner_domain_rulings_20261008.yaml"

NOISE_DROP_SENTINEL = "owner_finalized_noise_drop"  # D-2760 ratified provenance sentinel


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _load_drops() -> list[str]:
    """The declared noise_drop set, in declaration order (config-driven, C12)."""
    cfg = yaml.safe_load(RULINGS.read_text(encoding="utf-8"))
    return [str(i) for i in (cfg.get("noise_drop_excluded") or [])]


def _atomic_write_text(path: Path, text: str) -> None:
    """Crash-safe write: tempfile -> fsync -> os.replace (C6)."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def _write_csv(path: Path, fieldnames: list[str], rows: list[dict]) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=fieldnames, lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def clear_depth_authority(drops: list[str], drop_set: set[str], apply: bool) -> int:
    """Clear depth/depth_label/depth_source for declared noise_drop rows (fail-closed)."""
    rows = json.loads(DEPTH.read_text(encoding="utf-8"))
    by_id = {r["item_id"]: r for r in rows}
    unknown = [d for d in drops if d not in by_id]
    if unknown:
        raise SystemExit("FAIL-CLOSED: declared noise_drop row(s) not in the depth authority: "
                         + ", ".join(unknown))
    changed, already = [], []
    for r in rows:
        iid = r["item_id"]
        if iid not in drop_set:
            continue
        if r.get("depth") is None and r.get("depth_label") is None \
                and "noise_drop" in str(r.get("depth_source", "")):
            already.append(iid)
            continue
        changed.append(iid)
        r["depth"] = None
        r["depth_label"] = None
        r["depth_source"] = NOISE_DROP_SENTINEL
    if apply:
        _atomic_write_text(DEPTH, json.dumps(rows, indent=2, ensure_ascii=False) + "\n")
    print(f"  DEPTH_CORRECTED: {len(changed)} cleared, {len(already)} already clear "
          f"(of {len(drops)} declared)")
    return len(changed)


def clear_conformance(drops: list[str], drop_set: set[str], apply: bool) -> int:
    """Remove noise_drop rows from the golden conformance examples + ledger them excluded."""
    doc = json.loads(CONFORMANCE.read_text(encoding="utf-8"))
    examples = doc.get("examples", [])
    excluded = doc.get("excluded", [])
    already_excluded = {e.get("item_id") for e in excluded}
    kept, removed = [], []
    for e in examples:
        if e.get("item_id") in drop_set:
            removed.append(e.get("item_id"))
            if e.get("item_id") not in already_excluded:
                excluded.append({"item_id": e.get("item_id"),
                                 "reason": "owner noise_drop (D-2813: depth does not apply)"})
        else:
            kept.append(e)
    if removed:
        counts = doc.setdefault("counts", {})
        counts["total"] = len(kept)
        counts["by_depth_label"] = dict(Counter(e.get("depth_label") for e in kept))
        counts["by_depth_source"] = dict(Counter(e.get("depth_source") for e in kept))
        counts["name_normalized"] = []
        doc["examples"] = kept
        doc["excluded"] = excluded
        # keep the depth-map input sha256 honest (the depth authority changed)
        dm = (doc.get("inputs") or {}).get("depth_map")
        if dm:
            dm["sha256"] = _sha256_bytes(DEPTH.read_bytes())
        doc["_noise_drop_clear"] = {
            "rule": "D-2813: depth does not apply to a noise_drop row",
            "applied_at": datetime.now(timezone.utc).isoformat(),
            "removed": removed,
        }
    if apply:
        _atomic_write_text(CONFORMANCE, json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    print(f"  conformance: removed {len(removed)} noise_drop example(s) -> {len(kept)} examples, "
          f"{len(excluded)} excluded total")
    return len(removed)


def clear_views(drops: list[str], drop_set: set[str], apply: bool) -> int:
    """Clear the `depth` column to '' for declared noise_drop rows in both views."""
    total = 0
    for path in (VIEW_208, VIEW_150):
        rows = _read_csv(path)
        fieldnames = list(rows[0].keys()) if rows else []
        changed = 0
        for r in rows:
            iid = r.get("item_id")
            if iid in drop_set and r.get("depth") not in ("", None):
                r["depth"] = ""
                changed += 1
        if apply and changed:
            _write_csv(path, fieldnames, rows)
        total += changed
        print(f"  {path.name}: {changed} depth cell(s) cleared")
    return total


def main() -> int:
    parser = argparse.ArgumentParser(description="Clear depth for declared noise_drop rows (D-2813).")
    parser.add_argument("--apply", action="store_true", help="write (default dry-run)")
    args = parser.parse_args()
    drops = _load_drops()
    drop_set = set(drops)
    if not drops:
        raise SystemExit("FAIL-CLOSED: config declares no noise_drop_excluded set")
    print(f"noise_drop set ({len(drops)}): " + ", ".join(drops))
    n = clear_depth_authority(drops, drop_set, args.apply)
    n += clear_conformance(drops, drop_set, args.apply)
    n += clear_views(drops, drop_set, args.apply)
    print(f"{'applied' if args.apply else 'dry-run'}: {n} total cell/row change(s) across the depth faces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
